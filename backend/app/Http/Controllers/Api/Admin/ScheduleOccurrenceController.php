<?php

namespace App\Http\Controllers\Api\Admin;

use App\Http\Controllers\Controller;
use App\Http\Requests\Admin\SaveScheduleOccurrenceRequest;
use App\Http\Resources\Admin\AdminScheduleExceptionResource;
use App\Models\Course;
use App\Models\CourseSchedule;
use App\Services\Schedules\ScheduleOccurrenceService;
use Carbon\CarbonImmutable;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Response;
use Illuminate\Validation\ValidationException;

/**
 * Per-date overrides. The {date} segment is a generated start date — it must
 * actually be produced by the rule, otherwise the exception would be orphaned.
 */
class ScheduleOccurrenceController extends Controller
{
    public function __construct(private readonly ScheduleOccurrenceService $occurrences) {}

    public function update(
        SaveScheduleOccurrenceRequest $request,
        Course $course,
        CourseSchedule $schedule,
        string $date,
    ): JsonResponse {
        $this->assertGeneratedDate($schedule, $course, $date);
        $this->assertNotPastOccurrence($schedule, $date);

        $exception = $schedule->exceptions()->updateOrCreate(
            ['occurrence_date' => $date],
            $request->exceptionAttributes(),
        );

        // Always 200: PUT here is an idempotent upsert, so the caller should
        // not have to care whether the override already existed.
        return AdminScheduleExceptionResource::make($exception)
            ->response()
            ->setStatusCode(Response::HTTP_OK);
    }

    /**
     * Drop the override so the date falls back to the rule's own values.
     */
    public function destroy(Course $course, CourseSchedule $schedule, string $date): Response
    {
        $this->assertNotPastOccurrence($schedule, $date);
        $schedule->exceptions()->where('occurrence_date', $date)->delete();

        return response()->noContent();
    }

    private function assertGeneratedDate(CourseSchedule $schedule, Course $course, string $date): void
    {
        if ($this->occurrences->findOccurrence($schedule, $date, $course) === null) {
            throw ValidationException::withMessages([
                'date' => 'That date is not generated by this schedule.',
            ]);
        }
    }

    private function assertNotPastOccurrence(CourseSchedule $schedule, string $date): void
    {
        $timezone = (string) ($schedule->timezone ?: 'UTC');
        try {
            $today = CarbonImmutable::now($timezone)->startOfDay();
        } catch (\Throwable) {
            $today = CarbonImmutable::now('UTC')->startOfDay();
            $timezone = 'UTC';
        }

        $occurrenceDay = CarbonImmutable::parse($date, $timezone)->startOfDay();
        if ($occurrenceDay->lt($today)) {
            throw ValidationException::withMessages([
                'date' => 'Past occurrence dates cannot be edited or cancelled.',
            ]);
        }
    }
}
